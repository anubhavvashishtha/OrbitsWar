"""
rl/export_weights.py
====================
Export trained OrbitsNet weights as a pure-numpy Python file
that can be dropped into main.py without requiring PyTorch.

Output: rl_value_fn.py at the project root.

The exported file has the same interface as value_fn.py:
    NN_LOADED = True
    nn_value_score(feats, turn) -> float   # 0.0 – 1.0

Integration in main.py (add after existing value_fn imports):
    NN_LOADED = False
    try:
        from rl_value_fn import NN_LOADED, nn_value_score
    except ImportError:
        pass

Then blend in plan_moves where RL boost is computed:
    if NN_LOADED:
        nn_pw = nn_value_score(feats, world.step)
        rl_boost = 0.35 * (nn_pw - 0.5)

Usage
-----
    python rl/export_weights.py
"""
import sys
from pathlib import Path

ROOT         = Path(__file__).parent
PROJECT_ROOT = ROOT.parent
sys.path.insert(0, str(ROOT))

MODEL_PATH      = ROOT / "model.pt"
BEST_MODEL_PATH = ROOT / "model_best.pt"
OUTPUT_PATH     = PROJECT_ROOT / "rl_value_fn.py"


def export(model_path=None, output_path=OUTPUT_PATH):
    try:
        import torch, numpy as np
        from net import OrbitsNet
    except ImportError as e:
        print(f"Import error: {e}"); return False

    # prefer best checkpoint over latest
    if model_path is None:
        if BEST_MODEL_PATH.exists():
            model_path = BEST_MODEL_PATH
            print(f"Using best checkpoint: {BEST_MODEL_PATH}")
        else:
            model_path = MODEL_PATH

    if not Path(model_path).exists():
        print(f"No model found at {model_path}")
        print("Run replay_trainer.py and/or self_play_trainer.py first.")
        return False

    model = OrbitsNet()
    model.load_state_dict(torch.load(model_path, weights_only=True))
    model.eval()

    p = {n: v.detach().numpy() for n, v in model.named_parameters()}

    # Sequential: 0=Linear(30→128), 1=LayerNorm, [2=ReLU, 3=Dropout],
    #             4=Linear(128→64), [5=ReLU], 6=Linear(64→1), [7=Sigmoid]
    W1   = p['net.0.weight']                               # (128, 30)
    b1   = p['net.0.bias']                                 # (128,)
    ln_w = p.get('net.1.weight', np.ones(128))             # (128,)
    ln_b = p.get('net.1.bias',   np.zeros(128))            # (128,)
    W2   = p['net.4.weight']                               # (64, 128)
    b2   = p['net.4.bias']                                 # (64,)
    W3   = p['net.6.weight'][0]                            # (64,)
    b3   = float(p['net.6.bias'][0])

    def _f(a):
        return '[' + ','.join(f'{v:.8f}' for v in a.flatten()) + ']'
    def _m(m):
        return '[' + ','.join(_f(row) for row in m) + ']'

    code = [
        "# AUTO-GENERATED by rl/export_weights.py — do not edit",
        "import math as _m",
        "try:",
        "    import numpy as _np",
        "    _NUMPY = True",
        "except ImportError:",
        "    _NUMPY = False",
        "NN_LOADED = True",
        f"_W1={_m(W1)}",
        f"_b1={_f(b1)}",
        f"_ln_w={_f(ln_w)}",
        f"_ln_b={_f(ln_b)}",
        f"_W2={_m(W2)}",
        f"_b2={_f(b2)}",
        f"_W3={_f(W3)}",
        f"_b3={b3:.8f}",
        "",
        "if _NUMPY:",
        "    _nW1=_np.array(_W1,dtype=_np.float32)",
        "    _nb1=_np.array(_b1,dtype=_np.float32)",
        "    _nln_w=_np.array(_ln_w,dtype=_np.float32)",
        "    _nln_b=_np.array(_ln_b,dtype=_np.float32)",
        "    _nW2=_np.array(_W2,dtype=_np.float32)",
        "    _nb2=_np.array(_b2,dtype=_np.float32)",
        "    _nW3=_np.array(_W3,dtype=_np.float32)",
        "    def nn_value_score(feats,turn=250):",
        "        x=_np.array(feats,dtype=_np.float32)",
        "        h=_nW1@x+_nb1",
        "        mu=h.mean();std=_np.sqrt(h.var()+1e-5)",
        "        h=(h-mu)/std*_nln_w+_nln_b",
        "        h=_np.maximum(0,h)",
        "        h=_np.maximum(0,_nW2@h+_nb2)",
        "        z=float(_nW3@h+_b3)",
        "        return 1.0/(1.0+_m.exp(-z)) if z>=0 else _m.exp(z)/(1.0+_m.exp(z))",
        "else:",
        "    def _mv(W,x):",
        "        return[sum(W[i][j]*x[j] for j in range(len(x))) for i in range(len(W))]",
        "    def _ln(x,w,b):",
        "        n=len(x);mu=sum(x)/n;std=_m.sqrt(sum((v-mu)**2 for v in x)/n+1e-5)",
        "        return[(x[i]-mu)/std*w[i]+b[i] for i in range(n)]",
        "    def _relu(x): return[max(0.0,v) for v in x]",
        "    def nn_value_score(feats,turn=250):",
        "        h=_relu(_ln(_mv(_W1,feats),_ln_w,_ln_b))",
        "        h=_relu(_mv(_W2,h))",
        "        h=[h[i]+_b2[i] for i in range(len(h))]",
        "        h=_relu(h)",
        "        z=sum(_W3[i]*h[i] for i in range(len(h)))+_b3",
        "        return 1.0/(1.0+_m.exp(-z)) if z>=0 else _m.exp(z)/(1.0+_m.exp(z))",
    ]

    with open(output_path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(code) + '\n')

    sz = Path(output_path).stat().st_size / 1024
    print(f"Exported -> {output_path}  ({sz:.1f} KB)")
    print("\nAdd to main.py after the existing value_fn imports:")
    print("  NN_LOADED = False")
    print("  try:")
    print("      from rl_value_fn import NN_LOADED, nn_value_score")
    print("  except ImportError:")
    print("      pass")
    return True


if __name__ == "__main__":
    export()
